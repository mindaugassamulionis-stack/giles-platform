export function getLocalizedSymptomDiagnostics(
    cards: SymptomDiagnosticCard[],
    locale: AppLocale,
): SymptomDiagnosticCard[] {
    if (locale === 'lt') return cards;
    return cards.map((card) => {
        const tr = SYMPTOM_I18N[card.id]?.[locale];
        if (!tr) return card;
        return {
            ...card,
            badge: tr.badge,
            symptomTitle: tr.symptomTitle,
            shortSymptom: tr.shortSymptom,
            causePlain: tr.causePlain,
            fiveMinFixSteps: tr.fiveMinFixSteps,
            mistakeWarning: tr.mistakeWarning,
            calculatorLabel: tr.calculatorLabel,
            recommendedProducts: card.recommendedProducts.map((p, idx) => ({
                ...p,
                name: tr.products[idx]?.name || p.name,
                roleLabel: tr.products[idx]?.roleLabel || p.roleLabel,
                priceEstimateLabel: tr.products[idx]?.priceEstimateLabel || p.priceEstimateLabel,
            })),
        };
    });
}
